import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { mkdtemp, rm, readFile, mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createApp, validateEndpoint, validateResult } from '../server.mjs';

const verdict = { scene: 'Кот сидит за столом', comment: 'Кот хотя бы пришёл на совещание.', explanation: 'Работает контраст кота и офисной ситуации.', techniques: ['ирония'], relevance: 20, surprise: 18, humor: 20, delivery: 10 };
const listen = server => new Promise(resolve => server.listen(0, '127.0.0.1', () => resolve(`http://127.0.0.1:${server.address().port}`)));
const close = server => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); });
test('локальный адрес, шкала и граница зачёта', () => {
  assert.equal(validateEndpoint('http://localhost:1234/v1/'), 'http://localhost:1234/v1');
  for (const url of ['https://example.com/v1', 'http://127.0.0.1.evil.com/v1', 'http://localhost:1234/other', 'http://user:pass@localhost/v1']) assert.throws(() => validateEndpoint(url));
  assert.equal(validateResult({ ...verdict, relevance: 10, surprise: 10, humor: 20, delivery: 9 }).passed, false);
  assert.equal(validateResult({ ...verdict, relevance: 10, surprise: 10, humor: 20, delivery: 10 }).passed, true);
  assert.throws(() => validateResult({ ...verdict, humor: 31 }));
  assert.throws(() => validateResult({ ...verdict, humor: '25' }));
});
test('раунд → фото → модель → история → обратная связь → восстановление', async () => {
  const testRoot = path.resolve('work');
  await mkdir(testRoot, { recursive: true });
  const dataDir = await mkdtemp(path.join(testRoot, 'podpis-test-'));
  let lastRequest, calls = 0, fail = false;
  const lm = http.createServer(async (req, res) => {
    res.setHeader('Content-Type', 'application/json');
    if (req.url === '/v1/models') return res.end(JSON.stringify({ data: [{ id: 'qwen3-vl-test' }] }));
    let text = ''; for await (const chunk of req) text += chunk;
    lastRequest = JSON.parse(text); calls++;
    res.end(JSON.stringify({ choices: [{ message: { content: fail ? '{bad json' : JSON.stringify(verdict) } }] }));
  });
  const lmUrl = await listen(lm);
  const bytes = Buffer.from([255, 216, 255, 217]);
  let app = await createApp({ dataDir, photoFetch: async () => new Response(bytes, { headers: { 'content-type': 'image/jpeg' } }) });
  let base = await listen(app);
  const api = async (route, body) => { const r = await fetch(base + route, body === undefined ? {} : { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) }); return { status: r.status, body: await r.json() }; };
  try {
    assert.equal((await fetch(base + '/')).status, 200);
    assert.equal((await fetch(base + '/data/state.json')).status, 404);
    const cross = await fetch(base + '/api/settings', { method: 'POST', headers: { Origin: 'https://evil.test', 'Content-Type': 'application/json' }, body: '{}' }); assert.equal(cross.status, 403);
    const settingsResult = await api('/api/settings', { endpoint: lmUrl + '/v1', model: 'qwen3-vl-test', strictness: 'normal', memes: 'Пример мема', photoProvider: 'picsum', smartPhotos: false, token: 'test-secret' });
    assert.equal(settingsResult.status, 200, JSON.stringify(settingsResult.body));
    assert.equal((await api('/api/models')).body.models[0], 'qwen3-vl-test');
    const round = (await api('/api/round', {})).body;
    assert.deepEqual(Buffer.from(await (await fetch(base + round.image)).arrayBuffer()), bytes);
    assert.equal((await api('/api/judge', { roundId: round.id, caption: 'а'.repeat(51) })).status, 400);
    assert.equal((await api('/api/judge', { roundId: round.id, caption: '   ' })).status, 400);
    assert.equal((await api('/api/judge', { roundId: 'missing', caption: 'кот' })).status, 410);
    const result = (await api('/api/judge', { roundId: round.id, caption: 'Созвон, который мог быть мяу' })).body;
    assert.equal(result.score, 68); assert.equal(result.passed, true);
    assert.equal(lastRequest.messages[1].content[0].image_url.url, 'data:image/jpeg;base64,' + bytes.toString('base64'));
    assert.equal(lastRequest.response_format.type, 'json_schema');
    assert.equal((await api('/api/judge', { roundId: round.id, caption: 'Другой ответ' })).body.id, result.id); assert.equal(calls, 1);
    await api('/api/feedback', { id: result.id, feedback: 'high' });
    assert.equal((await api('/api/feedback', { id: result.id, comment: 'Отсылка к бессмысленным рабочим созвонам: кот заменяет коллегу.' })).status, 200);
    assert.equal((await api('/api/feedback', { id: result.id, comment: 'я'.repeat(1001) })).status, 400);
    const upload = (await api('/api/upload', { image: 'data:image/jpeg;base64,' + bytes.toString('base64') })).body;
    await api('/api/judge', { roundId: upload.id, caption: 'Вторая подпись' });
    assert.match(lastRequest.messages[0].content, /Созвон, который мог быть мяу/);
    assert.match(lastRequest.messages[0].content, /кот заменяет коллегу/);
    fail = true;
    const failedRound = (await api('/api/round', {})).body;
    assert.equal((await api('/api/judge', { roundId: failedRound.id, caption: 'Ошибка формата' })).status, 502);
    assert.equal((await api('/api/state')).body.history.length, 2);
    assert.ok(!(await readFile(path.join(dataDir, 'state.json'), 'utf8')).includes('test-secret'));
    await close(app); app = await createApp({ dataDir }); base = await listen(app);
    const restored = (await api('/api/state')).body;
    assert.equal(restored.history.length, 2); assert.equal(restored.history[0].feedback, 'high'); assert.equal(restored.hasToken, false);
    assert.equal(restored.settings.photoProvider, 'picsum');
    assert.match(restored.history[0].feedbackComment, /кот заменяет коллегу/);
    assert.equal(restored.memories.length, 1);
    const commentOnly = await api('/api/feedback', { id: restored.history[1].id, comment: 'Это добродушная самоирония.' });
    assert.equal(commentOnly.status, 200); assert.equal(commentOnly.body.feedback, null);
    await close(app);
    const saved = JSON.parse(await readFile(path.join(dataDir, 'state.json'), 'utf8'));
    saved.history = []; await writeFile(path.join(dataDir, 'state.json'), JSON.stringify(saved));
    app = await createApp({ dataDir }); base = await listen(app); fail = false;
    const oldMemoryRound = (await api('/api/upload', { image: 'data:image/jpeg;base64,' + bytes.toString('base64') })).body;
    await api('/api/judge', { roundId: oldMemoryRound.id, caption: 'Новый кот на созвоне' });
    assert.match(lastRequest.messages[0].content, /кот заменяет коллегу/);
    assert.match(lastRequest.messages[0].content, /добродушная самоирония/);
  } finally { await close(app); await close(lm); await rm(dataDir, { recursive: true, force: true }); }
});
